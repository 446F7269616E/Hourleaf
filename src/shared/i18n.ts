let resolvedLocale: ResolvedUiLocale = resolveSystemLocale();

export function configureLocale(
  preference: string | undefined,
  applyToDocument = true
): ResolvedUiLocale {
  resolvedLocale =
    preference === "zh-CN" || preference === "en" ? preference : resolveSystemLocale();
  if (applyToDocument && typeof document !== "undefined") {
    document.documentElement.lang = resolvedLocale;
    document.documentElement.dir = "ltr";
  }
  return resolvedLocale;
}

export function getResolvedLocale(): ResolvedUiLocale {
  return resolvedLocale;
}

export function t(
  key: MessageKey,
  variables: Readonly<Record<string, string | number>> = {}
): string {
  const template = resolvedLocale === "en" ? EN_MESSAGES[key] : ZH_MESSAGES[key];
  return template.replace(/\{([A-Za-z0-9_]+)\}/gu, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(variables, name) ? String(variables[name]) : match
  );
}

export function localizeDocumentTitle(
  page: "dashboard" | "plan" | "configuration" | "block" | "settings" | "popup"
): void {
  if (page === "popup") {
    document.title = "Hourleaf";
    return;
  }
  const key: MessageKey =
    page === "dashboard"
      ? "nav.dashboard"
      : page === "plan"
        ? "nav.plan"
        : page === "configuration"
          ? "nav.configuration"
          : page === "block"
            ? "nav.block"
            : "nav.settings";
  document.title = `${t(key)} · Hourleaf`;
}

function resolveSystemLocale(): ResolvedUiLocale {
  const language = globalThis.navigator?.languages?.[0] ?? globalThis.navigator?.language ?? "en";
  return language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}
